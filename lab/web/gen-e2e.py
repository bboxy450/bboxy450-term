#!/usr/bin/env python3
"""Generate lab/web/e2e.js from .bboxy/specs/e2e-acceptance.md §1. Stdlib only.

The checklist's promises have one source, the spec (#258 §4: "§1 of this spec, parsed"): every line `- **<ID>** <text>` under a
`###` group is one promise, in group order, ids unique. The lab loads the parse as `window.E2E_PROMISES = [...]`.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / ".bboxy" / "specs" / "e2e-acceptance.md"
OUT = pathlib.Path(__file__).resolve().parent / "e2e.js"


def main() -> int:
    text = SRC.read_text()
    sec = text.split("## 1.", 1)[1].split("\n## ", 1)[0]
    stated = int(re.search(r"(\d+) promises\.", sec).group(1))
    group, out = None, []
    for line in sec.splitlines():
        if line.startswith("### "):
            group = line[4:].strip()
        m = re.match(r"- \*\*([A-Z]\d+)\*\* (.+)", line)
        if m:
            out.append({"id": m.group(1), "group": group, "text": m.group(2).strip()})
    ids = [p["id"] for p in out]
    if len(ids) != len(set(ids)) or len(ids) != stated:
        print(f"e2e-acceptance §1: {len(ids)} promises parsed, {len(set(ids))} unique, {stated} stated", file=sys.stderr)
        return 1
    OUT.write_text("// generated by gen-e2e.py from .bboxy/specs/e2e-acceptance.md §1; do not edit\nwindow.E2E_PROMISES = " + json.dumps(out, indent=1, ensure_ascii=False) + ";\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(out)} promises")
    return 0


if __name__ == "__main__":
    sys.exit(main())
