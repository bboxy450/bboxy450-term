#!/usr/bin/env python3
"""Generate lab/web/tokens.js from design/tokens.toml and lab/web/logs.js from lab/web/logs/*.txt. Stdlib only.

The web lab loads tokens.js as a plain script (file:// has no modules), so the
output is `window.TOKENS = {...}`, `window.STYLE` and `window.SEAT_NAMES` (the seat-name pool) and nothing else. lab.js turns it into CSS
custom properties at runtime.
"""
import json
import pathlib
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "design" / "tokens.toml"
OUT = pathlib.Path(__file__).resolve().parent / "tokens.js"
STYLE = ROOT / "design" / "style.json"
LOGS = pathlib.Path(__file__).resolve().parent / "logs"
LOGS_OUT = pathlib.Path(__file__).resolve().parent / "logs.js"
SEAT_NAMES = ROOT / "crates" / "bbt-proto" / "src" / "seat_names.json"


def main() -> int:
    data = tomllib.loads(SRC.read_text())
    for key in ("color", "density", "radius", "sidebar", "strip", "glow", "motion", "seat_color", "font"):
        if key not in data:
            print(f"tokens.toml missing [{key}]", file=sys.stderr)
            return 1
    body = json.dumps(data, indent=2, sort_keys=True)
    style = json.loads(STYLE.read_text())
    # one source per value: a leaf path defined in both tokens.toml and style.json is an error, not a silent override
    def leaves(d, pre=""):
        for k, v in d.items():
            if isinstance(v, dict):
                yield from leaves(v, pre + k + ".")
            else:
                yield pre + k
    dup = sorted(set(leaves(data)) & set(leaves(style)))
    if dup:
        print("DUPLICATE token paths in tokens.toml and style.json (keep one source): " + ", ".join(dup), file=sys.stderr)
        return 2
    OUT.write_text(
        "// GENERATED by lab/web/gen-tokens.py from design/tokens.toml and design/style.json. Do not edit.\n"
        f"window.TOKENS = {body};\n"
        f"window.STYLE = {json.dumps(style, indent=2, sort_keys=True)};\n"
        # the product seat-name pool, one source with the backend (crates/bbt-proto/src/seat_names.json, T1)
        f"window.SEAT_NAMES = {json.dumps(json.loads(SEAT_NAMES.read_text())['pool'], ensure_ascii=False)};\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)} from {SRC.relative_to(ROOT)}")
    # Log fixtures for the showcase replay. fetch() is blocked on file://, so they ship as a script like tokens.js.
    logs = {f.stem: f.read_text() for f in sorted(LOGS.glob("*.txt"))}
    LOGS_OUT.write_text(
        "// GENERATED by lab/web/gen-tokens.py from lab/web/logs/*.txt. Do not edit.\n"
        f"window.LOGS = {json.dumps(logs, indent=2, sort_keys=True)};\n"
    )
    print(f"wrote {LOGS_OUT.relative_to(ROOT)} from {len(logs)} fixtures")
    return 0


if __name__ == "__main__":
    sys.exit(main())
