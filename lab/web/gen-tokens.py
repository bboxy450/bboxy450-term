#!/usr/bin/env python3
"""Generate lab/web/tokens.js from design/tokens.toml. Stdlib only.

The web lab loads tokens.js as a plain script (file:// has no modules), so the
output is `window.TOKENS = {...}` plus nothing else. lab.js turns it into CSS
custom properties at runtime.
"""
import json
import pathlib
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "design" / "tokens.toml"
OUT = pathlib.Path(__file__).resolve().parent / "tokens.js"


def main() -> int:
    data = tomllib.loads(SRC.read_text())
    for key in ("color", "density", "radius", "sidebar", "strip", "glow", "motion", "seat_color", "font"):
        if key not in data:
            print(f"tokens.toml missing [{key}]", file=sys.stderr)
            return 1
    body = json.dumps(data, indent=2, sort_keys=True)
    OUT.write_text(
        "// GENERATED by lab/web/gen-tokens.py from design/tokens.toml. Do not edit.\n"
        f"window.TOKENS = {body};\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)} from {SRC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
