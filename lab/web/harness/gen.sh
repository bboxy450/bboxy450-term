# Regenerate lab/web/harness-demo.js: run the real bboxy450-harness on the demo crate (demo/) with the scripted provider
# rounds (rounds/*.sse), offline and unattended (--yolo), then publish its envelopes with machine paths replaced.
#   HARNESS_BIN=path/to/bboxy450-harness sh lab/web/harness/gen.sh
set -eu
BIN=${HARNESS_BIN:?set HARNESS_BIN to a bboxy450-harness binary}
HERE=$(cd "$(dirname "$0")" && pwd)
WORK=$(mktemp -d)
HOMED=$(mktemp -d /tmp/bbh.XXXXXX)   # short: the session socket path must fit the 104-byte sun_path
trap 'rm -rf "$WORK" "$HOMED"' EXIT
cp -R "$HERE/demo" "$WORK/glyph-atlas"
set --; for r in "$HERE"/rounds/*.sse; do set -- "$@" --scripted "$r"; done
RUSTUP_HOME=${RUSTUP_HOME:-$HOME/.rustup} CARGO_HOME=${CARGO_HOME:-$HOME/.cargo} RUSTUP_TOOLCHAIN=${RUSTUP_TOOLCHAIN:-stable} HOME=$HOMED \
  "$BIN" -p "Glyphs flicker once the atlas fills up. Find it, fix it, prove it with the tests." --json \
  --cwd "$WORK/glyph-atlas" --sessions "$WORK/sessions" --yolo "$@" > "$WORK/out.jsonl"
"$BIN" check-transcript "$WORK/out.jsonl"
python3 -I - "$WORK" "$HERE/../harness-demo.js" <<'PY'
import json, os, sys
work, out = sys.argv[1], sys.argv[2]
real = os.path.realpath(work)
envs = []
for line in open(os.path.join(work, 'out.jsonl')):
    for w in {real, work}: line = line.replace(w + '/glyph-atlas', '~/src/glyph-atlas')
    line = line.replace('a//', 'a/').replace('b//', 'b/')
    envs.append(json.loads(line))
assert not any(p in json.dumps(envs) for p in ('/Users/', '/private/', '/var/folders/')), 'machine path leaked'
open(out, 'w').write('// GENERATED by lab/web/harness/gen.sh from lab/web/harness/demo and lab/web/harness/rounds/*.sse via a real bboxy450-harness run (scripted provider). Do not edit.\n'
    'window.HARNESS_SESSIONS = Object.assign(window.HARNESS_SESSIONS || {}, { "glyph-atlas": ' + json.dumps(envs, separators=(',', ':')) + ' });\n')
print(out, len(envs), 'envelopes')
PY
