# Regenerate lab/web/harness-acp.js from real bboxy450-harness session logs: ACP-agent sessions (claude-agent-acp,
# codex-acp, opencode, pi, omp) and the nemotron mermaid run, recorded by the harness parity work. Machine paths are
# replaced; every other byte is the log as the harness wrote it, including the rough edges the face must survive.
#   sh lab/web/harness/gen-acp.sh [FIXTURES_DIR]     default ../bboxy450-harness-parity/fixtures next to this repo
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
FIX=${1:-$HERE/../../../../bboxy450-harness-parity/fixtures}
python3 -I - "$FIX" "$HERE/../harness-acp.js" <<'PY'
import json, os, re, sys
fix, out = sys.argv[1], sys.argv[2]
names = ['acp-claude-acp', 'acp-codex-acp', 'acp-opencode', 'acp-pi', 'acp-omp', 'mermaid']
scrub = re.compile(r'/(?:private/)?(?:tmp|var/folders)/[^"\\\s]*?/scratchpad/(?:run/)?([A-Za-z0-9_.-]+)')
sessions = {}
for n in names:
    lines = open(os.path.join(fix, n + '.jsonl')).read().splitlines()
    sessions[n.replace('acp-', 'acp:', 1)] = [json.loads(scrub.sub(r'~/src/\1', l)) for l in lines if l.strip()]
blob = json.dumps(sessions, separators=(',', ':'))
assert not any(p in blob for p in ('/Users/', '/private/', '/var/folders/', '-Users-')), 'machine path leaked'
open(out, 'w').write('// GENERATED by lab/web/harness/gen-acp.sh from real bboxy450-harness session logs (ACP agents, mermaid). Do not edit.\n'
    'window.HARNESS_SESSIONS = Object.assign(window.HARNESS_SESSIONS || {}, ' + blob + ');\n')
print(out, {k: len(v) for k, v in sessions.items()})
PY
