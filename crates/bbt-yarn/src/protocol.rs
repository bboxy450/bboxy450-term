//! Values used by the constrained `protocol!` language. No effects execute here.

use core::marker::PhantomData;

/// An ordered list of effect values returned to the caller for interpretation.
pub type Effects<E> = alloc::vec::Vec<E>;

/// The outcome of one atomic, pure protocol step.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Decision<S, E, R, I> {
    /// All right-hand sides read the input state; effects retain lexical order.
    Accepted {
        /// The simultaneously updated state.
        next: S,
        /// Descriptions of work; the reducer never executes them.
        effects: Effects<E>,
    },
    /// The input state is retained and no effects are emitted.
    Rejected {
        /// A generated, finite rejection reason.
        reason: R,
    },
    /// The input state is retained and no effects are emitted.
    Ignored {
        /// A generated, finite ignore reason.
        reason: I,
    },
}

/// Implementation contract for enums generated by `protocol!`.
#[doc(hidden)]
pub trait FiniteDomain: Copy + Eq {
    /// Zero-based ordinal, below 63. Implementations are generated by the macro.
    fn ordinal(self) -> u32;
}

/// A finite value set over one declared protocol domain (at most 63 variants).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Set<D> {
    bits: u64,
    domain: PhantomData<D>,
}

impl<D: FiniteDomain> Set<D> {
    /// The empty set.
    pub const fn empty() -> Self {
        Self {
            bits: 0,
            domain: PhantomData,
        }
    }

    /// Whether this set contains the value.
    pub fn contains(self, value: D) -> bool {
        self.bits & (1_u64 << value.ordinal()) != 0
    }

    /// A new set containing the value; the input set is unchanged.
    pub fn with(self, value: D) -> Self {
        Self {
            bits: self.bits | (1_u64 << value.ordinal()),
            ..self
        }
    }

    /// A new set without the value; the input set is unchanged.
    pub fn without(self, value: D) -> Self {
        Self {
            bits: self.bits & !(1_u64 << value.ordinal()),
            ..self
        }
    }
}

impl<D: FiniteDomain> Default for Set<D> {
    fn default() -> Self {
        Self::empty()
    }
}
