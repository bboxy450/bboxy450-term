#!/bin/sh
# The operator's morning e2e session in one command: build the release app, start it with
# --ctl on the real Keychain custody, seat a Codex executor in this repository, and delegate
# the A-0 seeding task to it as the Oracle (decisions #260, #262, #269), answering Codex's
# hook review through the seat's own PTY under decision #270's rule.
# Usage: sh scripts/e2e-seed.sh            build, start (or reuse) the app, seat, delegate
#        sh scripts/e2e-seed.sh --dry-run  print every step, run nothing
#        sh scripts/e2e-seed.sh verify     the task's gate: 54 untested records, one per promise
set -eu
cd "$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)"
root=$(pwd)
task=.bboxy/tasks/2026-10-24-a0-seed-e2e.md
spec=.bboxy/specs/e2e-acceptance.md
# One fixed path: Codex approves the seat's hooks once per hook command path (#265).
bin=$root/target/release/bboxy450-term
issuer=${BBOXY_CTL_ISSUER:-Vesper, Oracle}

if [ "${1:-}" = verify ]; then
    # Every `- **<ID>**` line of §1 is a promise; every .bboxy/e2e record must be one of them,
    # once, type e2e, status untested.
    promises=$(sed -n 's/^- \*\*\([A-Z][0-9]*\)\*\* .*/\1/p' "$spec" | sort)
    records=$(for f in .bboxy/e2e/*.md; do
        [ -f "$f" ] || continue
        awk 'NR == 1 && $0 != "---" { exit } NR > 1 && $0 == "---" { exit }
            { gsub(/"/, "") }
            /^type:/ { t = $2 } /^status:/ { s = $2 } /^function:/ { fn = $2 }
            END { print fn, t, s }' "$f"
    done | sort)
    want=$(printf '%s\n' "$promises" | grep -c .)
    have=$(printf '%s\n' "$records" | grep -c . || true)
    bad=$(printf '%s\n' "$records" | awk 'NF && ($2 != "e2e" || $3 != "untested")')
    ids=$(printf '%s\n' "$records" | awk 'NF { print $1 }')
    echo "e2e-seed verify: $have records, $want promises"
    [ -z "$bad" ] || { echo "not type e2e / status untested:"; echo "$bad"; exit 1; }
    [ "$ids" = "$promises" ] || {
        echo "records and promises differ (missing, doubled or invented):"
        printf '%s\n' "$promises" > "${TMPDIR:-/tmp}/e2e-want.$$"
        printf '%s\n' "$ids" | diff "${TMPDIR:-/tmp}/e2e-want.$$" - || true
        rm -f "${TMPDIR:-/tmp}/e2e-want.$$"
        exit 1
    }
    echo "e2e-seed verify: pass"
    exit 0
fi

dry=false
case "${1:-}" in
    --dry-run) dry=true ;;
    "") ;;
    *) echo "usage: sh scripts/e2e-seed.sh [--dry-run | verify]" >&2; exit 2 ;;
esac
step() {
    printf '+ %s\n' "$*"
    if ! $dry; then "$@"; fi
}

number=$(sed -n 's/^number: *\([0-9][0-9]*\)$/\1/p' "$task" | head -1)
[ -n "$number" ] || { echo "e2e-seed: $task has no number" >&2; exit 2; }

# Release build: it always uses the Keychain, whatever BBOXY_TEST_CUSTODY says; unset it so
# nothing suggests otherwise.
unset BBOXY_TEST_CUSTODY
step env CARGO_TARGET_DIR="$root/target" cargo build --release --locked -p bboxy450-term

if ! $dry && "$bin" ctl seat ls >/dev/null 2>&1; then
    echo "e2e-seed: an app with --ctl is already running; using it"
else
    log=$root/target/e2e-seed-app.log
    printf '+ %s --ctl > %s &\n' "$bin" "$log"
    if ! $dry; then
        "$bin" --ctl > "$log" 2>&1 &
        tries=0
        until "$bin" ctl seat ls >/dev/null 2>&1; do
            tries=$((tries + 1))
            [ "$tries" -le 120 ] || { echo "e2e-seed: the app did not open ctl in 60 s; see $log" >&2; exit 1; }
            sleep 0.5
        done
    fi
fi

printf '+ %s ctl --as %s seat spawn codex --role executor --place tab --cwd %s --name e2e-seed\n' "$bin" "'$issuer'" "$root"
if $dry; then
    seat='<seat id>'
else
    spawned=$("$bin" ctl --as "$issuer" seat spawn codex --role executor --place tab --cwd "$root" --name e2e-seed)
    echo "$spawned"
    seat=$(printf '%s\n' "$spawned" | sed -n 's/.*"seat":"\([0-9A-Z]*\)".*/\1/p')
    [ -n "$seat" ] || { echo "e2e-seed: spawn failed" >&2; exit 1; }
fi

# Codex asks once per hook content to trust the seat's hooks (#265). Decision #270 and
# ctl-cli §4: answer it through our own PTY only when the count Codex shows equals the hooks
# the launch overlay installs (generated by `hook --list codex`, never a typed number) and
# the repository has no hook source of its own; otherwise stop and show the screen.
runlog=$root/target/e2e-seed-run.log
printf '+ %s hook --list codex   # the overlay hooks, from adapters/launch.rs\n' "$bin"
printf '+ %s ctl seat wait %s --text "Hooks need review|Ask Codex to do anything" --timeout 120000\n' "$bin" "$seat"
if ! $dry; then
    expected=$("$bin" hook --list codex)
    want=$(printf '%s\n' "$expected" | grep -c .)
    "$bin" ctl seat wait "$seat" --text 'Hooks need review|Ask Codex to do anything' --timeout 120000 >/dev/null
    screen=$("$bin" ctl seat screen "$seat" --human)
    if printf '%s\n' "$screen" | grep -q 'Hooks need review'; then
        have=$(printf '%s\n' "$screen" | sed -n 's/^ *\([0-9][0-9]*\) hooks* are new or changed\.$/\1/p' | head -1)
        repo_hooks=false
        [ -e "$root/.codex/hooks.json" ] && repo_hooks=true
        grep -qs '^\[hooks' "$root/.codex/config.toml" && repo_hooks=true
        {
            echo "== $(date -u +%Y-%m-%dT%H:%M:%SZ) Codex hook review, seat $seat"
            printf '%s\n' "$screen"
            echo "-- expected ($want, from hook --list codex):"
            printf '%s\n' "$expected"
        } >> "$runlog"
        menu=false
        printf '%s\n' "$screen" | grep -q '2\. Trust all and continue' && menu=true
        if [ "$have" != "$want" ] || $repo_hooks || ! $menu; then
            echo "-- refused: count $have, expected $want, repository hook source $repo_hooks, menu $menu" >> "$runlog"
            printf '%s\n' "$screen" >&2
            echo "e2e-seed: Codex lists ${have:-?} hooks, the app installs $want (repository hook source: $repo_hooks); not approving. Review it at the window; see $runlog" >&2
            exit 1
        fi
        "$bin" ctl seat key "$seat" down enter >/dev/null
        echo "-- approved: Trust all and continue ($want hooks, all the app's own)" >> "$runlog"
        echo "e2e-seed: trusted the app's own $want Codex hooks; logged in $runlog"
    fi
    "$bin" ctl seat wait "$seat" --text 'Ask Codex to do anything' --timeout 120000 >/dev/null
fi

printf '+ %s ctl --as %s task delegate %s %s\n' "$bin" "'$issuer'" "'#$number'" "$seat"
if ! $dry; then "$bin" ctl --as "$issuer" task delegate "#$number" "$seat"; fi

cat <<EOF

Seated $seat (Codex, executor) and delegated #$number.
Next, at the window:
  1. If the script stopped at Codex's hook review, review it there; otherwise nothing to approve.
  2. Watch the seat: it orients, then writes .bboxy/e2e records through the app.
  3. Completion: $bin ctl e2e list --human   ends with the summary: untested 54, missing 0, doubled 0;
     $bin ctl task get '#$number'          shows the report and its verify_result (exit 0).
EOF
